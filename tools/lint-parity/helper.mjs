// Babel Helper's page linter (custom-linter rules), booted over a bare window the way the
// Helper's own tests do (tests/linter-bridge.test.mjs), then configured with Helper's default
// settings (DEFAULT_EXTENSION_SETTINGS: highlighted words, disabled custom-linter rules).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

async function importHelperModule(helperDir, contents) {
  const { build } = createRequire(path.join(helperDir, 'package.json'))('esbuild');
  const result = await build({
    stdin: { contents, resolveDir: helperDir, loader: 'ts' },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    logLevel: 'silent',
  });
  return import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
}

export async function loadHelper(helperDir) {
  const { build } = createRequire(path.join(helperDir, 'package.json'))('esbuild');
  const result = await build({
    entryPoints: [path.join(helperDir, 'src/content/linter-bridge.ts')],
    absWorkingDir: helperDir,
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'chrome114',
    logLevel: 'silent',
  });
  let linter;
  const window = new EventTarget();
  const href = 'https://babel.test/transcription/RU-tx-gold-non-bg';
  Object.assign(window, {
    BabelMods: { unsafe: { services: {
      provide(name, service) {
        if (name === 'page.linter') linter = service;
        return () => {};
      },
    } } },
    fetch: async () => ({}),
    location: { origin: 'https://babel.test', pathname: '/transcription/RU-tx-gold-non-bg', search: '', href },
    history: {},
    setTimeout: () => 0,
    clearTimeout() {},
    setInterval: () => 0,
    clearInterval() {},
  });
  const document = { body: null, getElementById: () => null, querySelector: () => null, querySelectorAll: () => [] };
  const Element = class HTMLElement {};
  new Function('window', 'document', 'HTMLElement', 'Element', 'MutationObserver', 'IntersectionObserver', result.outputFiles[0].text)(
    window, document, Element, Element, undefined, undefined);
  if (!linter) throw new Error('Helper page linter did not register');
  const { DEFAULT_EXTENSION_SETTINGS: defaults } = await importHelperModule(
    helperDir, "export { DEFAULT_EXTENSION_SETTINGS } from './src/core/settings';");
  linter.configure({
    highlightedWordsEnabled: defaults.highlightedWordsEnabled,
    highlightedWords: defaults.highlightedWords,
    disabledCustomLinterRuleIds: defaults.disabledCustomLinterRuleIds,
  });
  return { linter, disabledRuleIds: [...defaults.disabledCustomLinterRuleIds] };
}

// The tables Studio's port of the custom linter needs (assets/helper-lint-data.json): the
// built-in rules (order, reason, severity) as the running linter reports them, the default
// highlighted words as Helper normalizes them, its interjection corrections, and the ё
// exception dictionary with its provenance.
export async function helperLintData(helperDir, { linter, disabledRuleIds }) {
  const source = await importHelperModule(helperDir, [
    "export { DEFAULT_HIGHLIGHTED_WORDS, normalizeHighlightedWords } from './src/core/highlighted-words';",
    "export { default as yoExceptions } from './src/features/custom-linter/linter/data/yo-exceptions.json';",
  ].join('\n'));
  const page = fs.readFileSync(path.join(helperDir, 'src/features/custom-linter/page.ts'), 'utf8');
  const specs = page.match(/const INTERJECTION_CORRECTION_SPECS = (\[[^;]*\]);/);
  if (!specs) throw new Error('INTERJECTION_CORRECTION_SPECS not found in page.ts');
  const { words, ...yoProvenance } = source.yoExceptions;
  return {
    source: 'Babel Helper custom linter; generated by tools/lint-parity/generate.mjs',
    rules: linter.getRules()
      .filter(({ id }) => !disabledRuleIds.includes(id))
      .map(({ id, reason, severity }) => ({ id, reason, severity })),
    highlighted_words: source.normalizeHighlightedWords(source.DEFAULT_HIGHLIGHTED_WORDS),
    interjection_corrections: new Function(`return ${specs[1]};`)(),
    yo_exceptions: { ...yoProvenance, words },
  };
}
