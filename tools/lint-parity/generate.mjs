// Generates Studio's linter data and its parity fixture from the two linters Studio replaces:
// Babel's native linter (Gold) configured for the gold-non-bg transcription variant, and the
// Babel Helper extension's custom linter. Babel's code is only read from the Babel checkout;
// what it produces goes into the Babel data bundle's stage, not into this repository.
//
//   node tools/lint-parity/generate.mjs [babelDir]
//
// babelDir defaults to ../babel beside this checkout. Writes
//   extensions/babel-lint/assets/babel-lint-data.json   gold-non-bg config per language + rule data
//   extensions/babel-lint/assets/helper-lint-data.json  Helper custom-linter rules + their data tables
//   target/babel-data/lint-parity.json                  corpus with both linters' issues (private)
// Seed the stage with the other bundle files first (`tools/update-babel-data.ps1 -Fetch`), then
// publish and pin the regenerated bundle with `tools/update-babel-data.ps1`.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { helperLintData, loadHelper } from './helper.mjs';
import { corpus } from './corpus.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const babelDir = path.resolve(process.argv[2] || path.join(repo, '..', 'babel'));
const { loadBabel } = createRequire(import.meta.url)('./babel.cjs');

// Babel's transcription languages (module 78100), in its order.
const LANGUAGES = ['EN', 'DE', 'HI', 'ZH', 'AR', 'KO', 'JA', 'PT', 'TL', 'RU', 'BN', 'TR', 'TH', 'ID', 'ES', 'FR', 'IT', 'VI', 'TE', 'TA', 'MR'];
// Rules whose input Babel fetches from its server (foreign-word dictionaries); Studio has no
// offline source for them.
const SERVER_DATA_RULES = new Set(['foreign-tag-dictionary', 'foreign-tag-code']);

const babel = loadBabel(babelDir);
const helperDir = path.join(babelDir, 'babel-helper-extension-repo');
const helper = await loadHelper(helperDir);

function goldNonBgProject(language) {
  return {
    id: `${language.toLowerCase()}-tx-gold-non-bg`,
    transcriptionVariant: 'gold-non-bg',
    language: language.toLowerCase(),
    category: null,
    productKind: null,
  };
}

const linters = new Map(LANGUAGES.map((language) => [language, new babel.Linter(goldNonBgProject(language))]));

function languageData(language) {
  const linter = linters.get(language);
  const { config } = linter;
  const registry = linter.getLinterRegistry();
  return {
    language,
    rules: registry.filter((rule) => !SERVER_DATA_RULES.has(rule.id)).map((rule) => rule.id),
    bracket_types: config.bracketTypes.map(({ open, close }) => ({ open, close })),
    bracket_tags: [...linter.validBracketTags],
    style_tags: [...linter.validStyleTags],
    foreign_style_tag: config.foreignStyleTag ?? null,
    mis_keyword: babel.config.gh(language),
    pro_keyword: babel.config.dB(language),
    unintelligible_tag: babel.config.hf(goldNonBgProject(language)),
    min_distance_seconds: config.minDistanceBetweenAnnotationsInSeconds,
  };
}

const registry = linters.get('RU').getLinterRegistry.call(Object.assign(Object.create(babel.Linter.prototype), {
  config: { enabledLinters: { has: () => true } },
}));
const { data } = babel;
const lintData = {
  source: 'Babel native linter (gold-non-bg) and Babel Helper custom linter; generated by tools/lint-parity/generate.mjs',
  registry: registry.map(({ id, type, severity }) => ({ id, type, severity })),
  reasons: data.e3,
  languages: LANGUAGES.map(languageData),
  hyphenated_words: [...babel.config.i5],
  language_codes: [...babel.languageCodes],
  filler_corrections: Object.fromEntries(data.e8),
  filler_suggestions: Object.fromEntries(data.e6),
  capitals_exempt_languages: [...data.eZ],
  banned_words: data.eG,
  terminal_punctuation: data.eV,
  default_terminal_punctuation: data.eY,
  comma_by_language: data.eq,
  traditional_chinese: [...data.eH].join(''),
};

function babelIssues(testCase) {
  const annotations = testCase.segments.map((segment) => ({
    id: segment.id,
    type: 'transcription',
    content: segment.text,
    startTimeInSeconds: segment.start,
    endTimeInSeconds: segment.end,
    processedRecordingId: segment.track,
    metadata: null,
  }));
  // Issues carry no rule id; the server-data rules report nothing here because Babel only has
  // their dictionaries after fetching them.
  return linters.get(testCase.language).lintAnnotations(annotations)
    .map((issue) => ({ id: issue.annotationId, source: 'gold', reason: issue.reason, severity: issue.severity }));
}

function helperIssues(testCase) {
  const entries = [...testCase.segments]
    .sort((left, right) => left.start - right.start)
    .map((segment) => ({ annotationId: segment.id, text: segment.text, speakerKey: segment.track }));
  return helper.linter.buildIssues(entries)
    .map((issue) => ({ id: issue.annotationId, source: 'helper', reason: issue.reason, severity: issue.severity }));
}

// Helper merges its issues into Babel's list, skipping ones whose (annotation, reason, severity)
// is already present (page.ts mergeNativeAndHelperIssues).
function merge(gold, helperList) {
  const merged = [...gold];
  const key = (issue) => `${issue.id}\u0000${issue.reason}\u0000${issue.severity}`;
  const seen = new Set(merged.map(key));
  for (const issue of helperList) {
    if (seen.has(key(issue))) continue;
    seen.add(key(issue));
    merged.push(issue);
  }
  return merged;
}

const fixture = {
  source: lintData.source,
  cases: corpus(lintData).map((testCase) => {
    const gold = babelIssues(testCase);
    const helperList = helperIssues(testCase);
    return { ...testCase, gold, helper: helperList, expected: merge(gold, helperList) };
  }),
};

const stage = path.join(repo, 'target/babel-data');
fs.mkdirSync(stage, { recursive: true });
fs.writeFileSync(path.join(repo, 'extensions/babel-lint/assets/babel-lint-data.json'), `${JSON.stringify(lintData, null, 1)}\n`);
fs.writeFileSync(path.join(repo, 'extensions/babel-lint/assets/helper-lint-data.json'), `${JSON.stringify(await helperLintData(helperDir, helper), null, 1)}\n`);
fs.writeFileSync(path.join(stage, 'lint-parity.json'), `${JSON.stringify(fixture, null, 1)}\n`);
const issueCount = fixture.cases.reduce((total, testCase) => total + testCase.expected.length, 0);
console.log(`languages ${lintData.languages.length}, cases ${fixture.cases.length}, issues ${issueCount}`);
