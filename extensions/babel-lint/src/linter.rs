//! Transcript lint: exactly the two linters Studio replaces.
//!
//! - [`gold`]: Babel's native linter (Gold) with its gold-non-bg configuration for the project's
//!   language, over the project's transcription annotations.
//! - [`helper`]: the Babel Helper extension's custom-linter rules.
//!
//! Helper issues merge into Gold's list the way Helper does it: an issue whose (annotation,
//! reason, severity) is already listed is dropped. Issues Babel's server reported for the task
//! (the server runs the same Gold linter) come first; a local issue repeating one of them is
//! dropped too. The parity fixture (`lint-parity.json` from the Babel data bundle, generated by
//! `tools/lint-parity`; see `crate::data`) pins both linters against the originals.

pub(crate) mod gold;
mod helper;
mod low_confidence;

use std::collections::{BTreeMap, HashMap, HashSet};

use studio_core::{Project, Segment};

use crate::project_lint_tag_config::resolve_babel_project_lint_tag_config;
use gold::{GoldAnnotation, lint_annotations};
use helper::{HelperEntry, helper_issues};
pub use low_confidence::has_unresolved_low_confidence_word;

fn is_transcription(segment: &Segment) -> bool {
    segment
        .metadata
        .get("type")
        .and_then(serde_json::Value::as_str)
        .unwrap_or("transcription")
        == "transcription"
}

/// Gold's rule for unresolved low-confidence words; its warnings are cleared by resolving the
/// words, not by acknowledging the warning.
pub const UNRESOLVED_LOW_CONFIDENCE_RULE: &str = "unresolved-low-confidence";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LintStatus {
    pub severity: LintSeverity,
    pub message: String,
    pub kind: LintKind,
}

impl LintStatus {
    pub fn pass(message: impl Into<String>) -> Self {
        Self {
            severity: LintSeverity::Pass,
            message: message.into(),
            kind: LintKind::Pass,
        }
    }

    pub fn is_assertable_warning(&self) -> bool {
        self.severity == LintSeverity::Warning
            && self.kind != LintKind::Gold(UNRESOLVED_LOW_CONFIDENCE_RULE)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LintSeverity {
    Pass,
    Warning,
    Error,
}

/// Where an issue comes from; Gold and Helper issues carry their rule id.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LintKind {
    Pass,
    BabelServer,
    Gold(&'static str),
    Helper(&'static str),
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ServerLintIssue {
    pub annotation_id: String,
    pub reason: String,
    pub severity: LintSeverity,
}

#[derive(Clone)]
pub struct ServerLintSnapshot {
    pub revision: u64,
    pub issues: Vec<ServerLintIssue>,
    issue_indices_by_annotation_id: BTreeMap<String, Vec<usize>>,
}

impl std::fmt::Debug for ServerLintSnapshot {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("ServerLintSnapshot")
            .field("revision", &self.revision)
            .field("issues", &self.issues)
            .finish()
    }
}

impl PartialEq for ServerLintSnapshot {
    fn eq(&self, other: &Self) -> bool {
        self.revision == other.revision && self.issues == other.issues
    }
}

impl Eq for ServerLintSnapshot {}

impl ServerLintSnapshot {
    pub fn new(revision: u64, issues: Vec<ServerLintIssue>) -> Self {
        let mut issue_indices_by_annotation_id: BTreeMap<String, Vec<usize>> = BTreeMap::new();
        for (index, issue) in issues.iter().enumerate() {
            issue_indices_by_annotation_id
                .entry(issue.annotation_id.clone())
                .or_default()
                .push(index);
        }
        Self {
            revision,
            issues,
            issue_indices_by_annotation_id,
        }
    }

    fn issue_indices(&self, annotation_id: &str) -> &[usize] {
        self.issue_indices_by_annotation_id
            .get(annotation_id)
            .map(Vec::as_slice)
            .unwrap_or_default()
    }
}

/// Lint for every transcription annotation of one project state.
pub struct ProjectLintAnalysis {
    issues_by_segment_id: HashMap<String, Vec<LintStatus>>,
}

impl ProjectLintAnalysis {
    pub fn new(project: &Project) -> Self {
        let config = resolve_babel_project_lint_tag_config(project);
        let transcriptions = project
            .segments
            .iter()
            .filter(|segment| is_transcription(segment))
            .collect::<Vec<_>>();
        let annotations = transcriptions
            .iter()
            .map(|segment| GoldAnnotation {
                id: &segment.id,
                text: &segment.text,
                start_seconds: segment.start_seconds,
                end_seconds: segment.end_seconds,
                track_id: &segment.lane_id,
                unresolved_low_confidence: has_unresolved_low_confidence_word(segment),
            })
            .collect::<Vec<_>>();
        let mut in_time_order = transcriptions;
        in_time_order.sort_by(|left, right| left.start_seconds.total_cmp(&right.start_seconds));
        let entries = in_time_order
            .iter()
            .map(|segment| HelperEntry {
                annotation_id: &segment.id,
                text: &segment.text,
                speaker_key: &segment.lane_id,
            })
            .collect::<Vec<_>>();

        let mut issues_by_segment_id: HashMap<String, Vec<LintStatus>> = HashMap::new();
        let mut listed = HashSet::new();
        for issue in lint_annotations(config.gold(), &annotations) {
            listed.insert((
                issue.annotation_id.clone(),
                issue.reason.clone(),
                issue.severity,
            ));
            issues_by_segment_id
                .entry(issue.annotation_id)
                .or_default()
                .push(LintStatus {
                    severity: issue.severity,
                    message: issue.reason,
                    kind: LintKind::Gold(issue.rule_id),
                });
        }
        for issue in helper_issues(&entries) {
            if !listed.insert((
                issue.annotation_id.clone(),
                issue.reason.to_string(),
                issue.severity,
            )) {
                continue;
            }
            issues_by_segment_id
                .entry(issue.annotation_id)
                .or_default()
                .push(LintStatus {
                    severity: issue.severity,
                    message: issue.reason.to_string(),
                    kind: LintKind::Helper(issue.rule_id),
                });
        }
        Self {
            issues_by_segment_id,
        }
    }

    pub fn lint_segment_issues(&self, segment: &Segment) -> Vec<LintStatus> {
        self.issues_by_segment_id
            .get(&segment.id)
            .cloned()
            .unwrap_or_default()
    }
}

/// A row's issues: the server's first, then local ones it did not already report.
pub fn combine_server_and_local_issues(
    mut server: Vec<LintStatus>,
    local: Vec<LintStatus>,
) -> Vec<LintStatus> {
    let reported = server
        .iter()
        .map(|issue| (issue.message.clone(), issue.severity))
        .collect::<HashSet<_>>();
    server.extend(
        local
            .into_iter()
            .filter(|issue| !reported.contains(&(issue.message.clone(), issue.severity))),
    );
    server
}

pub fn server_lint_issues_for_segment(
    snapshot: Option<&ServerLintSnapshot>,
    segment: &Segment,
) -> Vec<LintStatus> {
    let Some(snapshot) = snapshot else {
        return Vec::new();
    };

    let direct_indices = snapshot.issue_indices(&segment.id);
    let source_indices = segment
        .source_annotation_id
        .as_deref()
        .filter(|source_id| *source_id != segment.id.as_str())
        .map(|source_id| snapshot.issue_indices(source_id))
        .unwrap_or_default();
    let mut direct_position = 0;
    let mut source_position = 0;
    let mut issues = Vec::with_capacity(direct_indices.len() + source_indices.len());
    while direct_position < direct_indices.len() || source_position < source_indices.len() {
        let direct_index = direct_indices.get(direct_position).copied();
        let source_index = source_indices.get(source_position).copied();
        let index = match (direct_index, source_index) {
            (Some(direct), Some(source)) if direct <= source => {
                direct_position += 1;
                if direct == source {
                    source_position += 1;
                }
                direct
            }
            (Some(_), Some(source)) => {
                source_position += 1;
                source
            }
            (Some(direct), None) => {
                direct_position += 1;
                direct
            }
            (None, Some(source)) => {
                source_position += 1;
                source
            }
            (None, None) => break,
        };
        let issue = &snapshot.issues[index];
        issues.push(LintStatus {
            severity: issue.severity,
            message: issue.reason.clone(),
            kind: LintKind::BabelServer,
        });
    }
    issues
}

pub fn server_lint_issue_matches_segment(issue: &ServerLintIssue, segment: &Segment) -> bool {
    issue.annotation_id == segment.id
        || segment
            .source_annotation_id
            .as_deref()
            .is_some_and(|source_id| issue.annotation_id == source_id)
}

pub fn warning_key(segment: &Segment, lint: &LintStatus) -> Option<String> {
    lint.is_assertable_warning()
        .then(|| format!("{}::{}", segment.id, lint.message))
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use serde::Deserialize;
    use studio_core::{AudioLane, Project, Segment, Speaker};

    use super::{
        LintKind, LintSeverity, LintStatus, ProjectLintAnalysis, ServerLintIssue,
        ServerLintSnapshot, combine_server_and_local_issues, server_lint_issues_for_segment,
    };
    use crate::project_lint_tag_config::META_BABEL_LINT_TAG_LANGUAGE;

    #[derive(Deserialize)]
    struct Fixture {
        cases: Vec<FixtureCase>,
    }

    #[derive(Deserialize)]
    struct FixtureCase {
        name: String,
        language: String,
        segments: Vec<FixtureSegment>,
        expected: Vec<FixtureIssue>,
    }

    #[derive(Deserialize)]
    struct FixtureSegment {
        id: String,
        text: String,
        start: f64,
        end: f64,
        track: String,
    }

    #[derive(Deserialize)]
    struct FixtureIssue {
        id: String,
        source: String,
        reason: String,
        severity: String,
    }

    /// Every corpus transcript lints exactly like Babel's gold-non-bg linter with Helper's
    /// issues merged in: same issues, sources, severities and order per row.
    #[test]
    fn project_lint_matches_gold_and_helper_on_the_parity_corpus() {
        let Some(json) = crate::data::lint_parity_json(
            "project_lint_matches_gold_and_helper_on_the_parity_corpus",
        ) else {
            return;
        };
        let fixture: Fixture = serde_json::from_str(&json).expect("parity fixture");
        for case in fixture.cases {
            let project = fixture_project(&case);
            let analysis = ProjectLintAnalysis::new(&project);
            for segment in &project.segments {
                let actual = analysis
                    .lint_segment_issues(segment)
                    .into_iter()
                    .map(|issue| {
                        let source = match issue.kind {
                            LintKind::Gold(_) => "gold",
                            LintKind::Helper(_) => "helper",
                            other => panic!("unexpected local lint kind {other:?}"),
                        };
                        (
                            source.to_string(),
                            issue.message,
                            severity_name(issue.severity),
                        )
                    })
                    .collect::<Vec<_>>();
                let expected = case
                    .expected
                    .iter()
                    .filter(|issue| issue.id == segment.id)
                    .map(|issue| {
                        (
                            issue.source.clone(),
                            issue.reason.clone(),
                            issue.severity.clone(),
                        )
                    })
                    .collect::<Vec<_>>();
                assert_eq!(actual, expected, "{} / {}", case.name, segment.id);
            }
        }
    }

    #[test]
    fn non_transcription_annotations_are_not_linted() {
        let mut project = project_with_segments(vec![
            segment("speech", "Да.", 0.0, 3.0),
            segment("noise", "", 1.0, 2.0),
        ]);
        project.segments[1]
            .metadata
            .insert("type".to_string(), serde_json::json!("background_noise"));
        let analysis = ProjectLintAnalysis::new(&project);

        assert_eq!(
            analysis.lint_segment_issues(&project.segments[0]),
            Vec::new()
        );
        assert_eq!(
            analysis.lint_segment_issues(&project.segments[1]),
            Vec::new()
        );
    }

    #[test]
    fn local_issues_the_server_already_reported_are_listed_once() {
        let server = vec![LintStatus {
            severity: LintSeverity::Error,
            message: "Double spaces are not allowed in text.".to_string(),
            kind: LintKind::BabelServer,
        }];
        let local = vec![
            LintStatus {
                severity: LintSeverity::Error,
                message: "Double spaces are not allowed in text.".to_string(),
                kind: LintKind::Gold("double-spaces"),
            },
            LintStatus {
                severity: LintSeverity::Error,
                message: "Double spaces are not allowed.".to_string(),
                kind: LintKind::Helper("double-spaces"),
            },
        ];

        assert_eq!(
            combine_server_and_local_issues(server, local)
                .into_iter()
                .map(|issue| issue.kind)
                .collect::<Vec<_>>(),
            vec![LintKind::BabelServer, LintKind::Helper("double-spaces")]
        );
    }

    #[test]
    fn server_lint_index_preserves_order_and_multiplicity_across_both_ids() {
        let mut segment = segment("internal", "clean", 0.0, 1.0);
        segment.source_annotation_id = Some("source".to_string());
        let snapshot = ServerLintSnapshot::new(
            0,
            vec![
                server_issue("source", "source first", LintSeverity::Warning),
                server_issue("internal", "internal second", LintSeverity::Error),
                server_issue("source", "source third", LintSeverity::Warning),
                server_issue("unmatched", "not returned", LintSeverity::Error),
                server_issue("internal", "internal fourth", LintSeverity::Error),
            ],
        );
        assert_eq!(
            server_lint_issues_for_segment(Some(&snapshot), &segment)
                .into_iter()
                .map(|issue| issue.message)
                .collect::<Vec<_>>(),
            vec![
                "source first",
                "internal second",
                "source third",
                "internal fourth",
            ]
        );

        segment.source_annotation_id = Some(segment.id.clone());
        let coincident = ServerLintSnapshot::new(
            0,
            vec![
                server_issue("internal", "duplicate one", LintSeverity::Warning),
                server_issue("internal", "duplicate two", LintSeverity::Warning),
            ],
        );
        assert_eq!(
            server_lint_issues_for_segment(Some(&coincident), &segment)
                .into_iter()
                .map(|issue| issue.message)
                .collect::<Vec<_>>(),
            vec!["duplicate one", "duplicate two"]
        );
    }

    fn severity_name(severity: LintSeverity) -> String {
        match severity {
            LintSeverity::Error => "error",
            LintSeverity::Warning => "warning",
            LintSeverity::Pass => "pass",
        }
        .to_string()
    }

    fn server_issue(annotation_id: &str, reason: &str, severity: LintSeverity) -> ServerLintIssue {
        ServerLintIssue {
            annotation_id: annotation_id.to_string(),
            reason: reason.to_string(),
            severity,
        }
    }

    fn fixture_project(case: &FixtureCase) -> Project {
        let mut lanes: Vec<AudioLane> = Vec::new();
        for track in case.segments.iter().map(|segment| &segment.track) {
            if !lanes.iter().any(|lane| &lane.id == track) {
                lanes.push(AudioLane {
                    id: track.clone(),
                    speaker_id: track.clone(),
                    label: track.clone(),
                    source_path: format!("{track}.wav"),
                });
            }
        }
        Project {
            id: "task".to_string(),
            name: "Task".to_string(),
            speakers: lanes
                .iter()
                .map(|lane| Speaker {
                    id: lane.id.clone(),
                    label: lane.label.clone(),
                })
                .collect(),
            lanes,
            segments: case
                .segments
                .iter()
                .map(|fixture| Segment {
                    lane_id: fixture.track.clone(),
                    speaker_id: fixture.track.clone(),
                    ..segment(&fixture.id, &fixture.text, fixture.start, fixture.end)
                })
                .collect(),
            metadata: BTreeMap::from([(
                META_BABEL_LINT_TAG_LANGUAGE.to_string(),
                case.language.clone(),
            )]),
        }
    }

    fn project_with_segments(segments: Vec<Segment>) -> Project {
        Project {
            id: "task".to_string(),
            name: "Task".to_string(),
            speakers: vec![Speaker {
                id: "speaker-1".to_string(),
                label: "Speaker 1".to_string(),
            }],
            lanes: vec![AudioLane {
                id: "lane-1".to_string(),
                speaker_id: "speaker-1".to_string(),
                label: "Speaker 1".to_string(),
                source_path: "speaker_1.wav".to_string(),
            }],
            segments,
            metadata: BTreeMap::new(),
        }
    }

    fn segment(id: &str, text: &str, start_seconds: f64, end_seconds: f64) -> Segment {
        Segment {
            id: id.to_string(),
            source_annotation_id: None,
            speaker_id: "speaker-1".to_string(),
            lane_id: "lane-1".to_string(),
            start_seconds,
            end_seconds,
            text: text.to_string(),
            metadata: BTreeMap::new(),
        }
    }
}
